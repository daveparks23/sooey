/// The piglet: front view, all head and ears, deliberately top-heavy so it
/// reads as a baby.
///
/// This departs from the spec's reference piglet, which does not survive
/// rendering at 1:1. That sprite's eyes are single-pixel gaps, which splits the
/// head into three separate chunks and reads as two blobs rather than a face —
/// exactly the failure its own style note warns about ("no single-pixel
/// details"). Here the eyes are 2x2 holes in a solid mass, the ears widen down
/// into the skull instead of floating above it, and the snout is its own
/// rounded shape carrying the nostrils. The adult reference sprite reads
/// perfectly and is kept verbatim.

