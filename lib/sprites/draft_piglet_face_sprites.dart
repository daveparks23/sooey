/// DRAFT — the piglet, as a front-facing outlined face.
///
/// Built on the adult's anatomy so the two read as the same animal, then given
/// baby proportions. What actually makes something read as young at this size
/// is not simply being smaller — a scaled-down adult reads as a distant adult.
/// It is the ratio between the features:
///
///   * head 13 wide against the adult's 15, but sitting on a body barely half
///     the adult's width — a big head on a tiny body
///   * ears as wide as the adult's on a narrower skull, so they dominate
///   * eyes are solid 2x2 blocks rather than the adult's 3-dot marks
///   * snout three rows deep instead of five, because a snout lengthens with
///     age and a short one is the single most piglet-ish feature available
///
/// Shared layout, so a mood swap only ever touches the eye rows:
///
///   rows 2-5    ears
///   rows 3-11   head outline, left edge x9, right edge x21
///   rows 6-7    eyes            <- where mood lives
///   rows 8-10   snout, nostrils on row 9
///   rows 11-15  body and feet, tapering to a narrow stance
///
/// Feet stay on row 15, the same floor the adult stands on.

