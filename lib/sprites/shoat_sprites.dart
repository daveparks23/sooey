/// Rooting: snout on the floor, hindquarters up.
///
/// The two frames are the whole animation — the pig drops its head to the
/// ground, then lifts it to chew, and back down. That nod is what makes it read
/// as feeding; a mouth notch alone just looks like an idle pig with a chipped
/// face.
///
/// The pose is carried entirely by the spine: it slopes from a high rump on the
/// left down to a snout resting on the same row as the feet. The 2x2 eye hole
/// is what tells you which end is the head once the silhouette has flattened
/// out — without it the shape is ambiguous.
