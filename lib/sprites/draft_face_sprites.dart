/// DRAFT — a front-facing, outlined pig, exploring Dave's direction.
///
/// Not wired into the game. Registered under `draft.*` so the gallery renders
/// it beside the current cast for comparison.
///
/// The layout every pose shares, so the face stays recognisably the same
/// animal across moods:
///
///   rows 0-3    ears
///   rows 1-11   head outline, left edge x8, right edge x22
///   rows 4-5    eyes            <- where mood lives
///   rows 6-10   snout, nostrils on row 8
///   rows 11-15  body and feet
///
/// The snout owns the middle of the face, which is where a mouth would go on
/// any other creature. That is the whole design problem with a front view: the
/// mouth is not available as an expressive channel, so **the eyes and ears have
/// to carry every mood**, and the snout stays put as the thing that says "pig".
///
/// Feet stay on row 15 in every frame of every pose. A pose that lifts them
/// reads as the pig hovering rather than moving.

